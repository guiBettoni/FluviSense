-- 001: esquema base do MVP de 2026.1 (reconstruído em 21/10/2026).
--
-- Este arquivo não existia no repositório: as tabelas tinham sido criadas direto no Supabase.
-- Foi reconstruído a partir dos modelos SQLAlchemy da época (versão "Estado original recebido" do histórico do Git).
-- Usa "if not exists", então não altera um banco onde essas tabelas já existem.
-- A partir da 004, a aplicação deixa de usar sensors, sensor_readings, residents,
-- shelters e manual_occurrences; elas ficam no banco só como histórico.

begin;

create table if not exists public.sensors (
  id integer generated by default as identity primary key,
  sensor_code varchar(50) not null unique,
  name varchar(120) not null,
  neighborhood varchar(120),
  location_description varchar(255),
  latitude double precision not null,
  longitude double precision not null,
  threshold_yellow numeric(8,2) not null,
  threshold_orange numeric(8,2) not null,
  threshold_red numeric(8,2) not null,
  current_level numeric(8,2) not null default 0,
  current_status varchar(20) not null default 'verde',
  active boolean not null default true,
  last_reading_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.sensor_readings (
  id integer generated by default as identity primary key,
  sensor_id integer not null references public.sensors (id),
  water_level_cm numeric(8,2) not null,
  origin varchar(30) not null,
  status_generated varchar(20) not null,
  is_valid boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists sensor_readings_sensor_id_idx on public.sensor_readings (sensor_id);

create table if not exists public.residents (
  id integer generated by default as identity primary key,
  name varchar(120) not null,
  whatsapp varchar(30) not null,
  email varchar(160) not null,
  neighborhood varchar(120) not null,
  street varchar(200) not null,
  consent_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.manual_occurrences (
  id integer generated by default as identity primary key,
  sensor_id integer not null references public.sensors (id),
  status varchar(20) not null default 'vermelho',
  reason text not null,
  operator varchar(120) not null default 'operador',
  closed_at timestamptz,
  closed_by varchar(120),
  created_at timestamptz not null default now()
);

create table if not exists public.audit_events (
  id integer generated by default as identity primary key,
  actor varchar(120) not null,
  action varchar(120) not null,
  entity varchar(120) not null,
  details text,
  created_at timestamptz not null default now()
);

create table if not exists public.shelters (
  id integer generated by default as identity primary key,
  name varchar(160) not null,
  latitude double precision not null,
  longitude double precision not null,
  capacity integer not null,
  occupancy integer not null default 0,
  active boolean not null default true
);

commit;
