-- 004: modelo de monitoramento por distância (versão 2.0).
--
-- Cria rios, pontos de monitoramento, medições de distância e ocorrências manuais por ponto.
-- Não apaga nem altera as tabelas antigas. Copia os sensores antigos como pontos
-- (sem critérios, porque os limiares antigos eram de nível e não valem para distância)
-- e copia as ocorrências manuais antigas. As leituras antigas (nível) não são copiadas,
-- porque não há como convertê-las em distância; continuam em sensor_readings.

begin;

create table if not exists public.rivers (
  id integer generated by default as identity primary key,
  name varchar(120) not null unique,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.monitoring_points (
  id integer generated by default as identity primary key,
  code varchar(50) not null unique,
  name varchar(120) not null,
  river_id integer references public.rivers (id),
  neighborhood varchar(120),
  location_description varchar(255),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  attention_distance_cm numeric(8,2),
  alert_distance_cm numeric(8,2),
  critical_distance_cm numeric(8,2),
  criteria_provisional boolean not null default true,
  criteria_note text,
  min_valid_distance_cm numeric(8,2) check (min_valid_distance_cm > 0),
  max_valid_distance_cm numeric(8,2) check (max_valid_distance_cm > 0),
  max_jump_cm numeric(8,2) check (max_jump_cm > 0),
  stale_after_minutes integer not null default 720 check (stale_after_minutes > 0),
  device_key_hash varchar(64),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  constraint monitoring_points_criteria_check check (
    (attention_distance_cm is null and alert_distance_cm is null and critical_distance_cm is null)
    or (attention_distance_cm > alert_distance_cm and alert_distance_cm > critical_distance_cm and critical_distance_cm > 0)
  ),
  constraint monitoring_points_valid_range_check check (
    min_valid_distance_cm is null or max_valid_distance_cm is null or min_valid_distance_cm < max_valid_distance_cm
  )
);

create table if not exists public.measurements (
  id integer generated by default as identity primary key,
  point_id integer not null references public.monitoring_points (id),
  distance_cm numeric(8,2) not null,
  unit varchar(10) not null default 'cm' check (unit = 'cm'),
  origin varchar(20) not null check (origin in ('sensor', 'manual', 'simulada')),
  measured_at timestamptz not null,
  received_at timestamptz not null default now(),
  validity varchar(20) not null check (validity in ('valida', 'suspeita', 'invalida')),
  validity_reason varchar(255),
  reference_cm numeric(8,2),
  classification varchar(20) check (classification in ('verde', 'amarelo', 'laranja', 'vermelho', 'sem_criterio')),
  created_by varchar(160)
);
create index if not exists measurements_point_measured_idx on public.measurements (point_id, measured_at);

create table if not exists public.point_occurrences (
  id integer generated by default as identity primary key,
  point_id integer not null references public.monitoring_points (id),
  classification varchar(20) not null check (classification in ('amarelo', 'laranja', 'vermelho')),
  reason text not null,
  opened_by varchar(160) not null,
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  closed_by varchar(160)
);
create index if not exists point_occurrences_point_id_idx on public.point_occurrences (point_id);
create unique index if not exists point_occurrences_one_open_idx
  on public.point_occurrences (point_id) where closed_at is null;

-- Sensores antigos viram pontos sem rio e sem critérios.
insert into public.monitoring_points (code, name, neighborhood, location_description, latitude, longitude, active, created_at, criteria_note)
select s.sensor_code, s.name, s.neighborhood, s.location_description, s.latitude, s.longitude, s.active, s.created_at,
       'Ponto migrado do modelo anterior (limiares em nível de água). Configure rio e critérios por distância.'
from public.sensors s
on conflict (code) do nothing;

-- Ocorrências manuais antigas (sempre vermelho no modelo anterior).
insert into public.point_occurrences (point_id, classification, reason, opened_by, opened_at, closed_at, closed_by)
select p.id, 'vermelho', m.reason, m.operator, m.created_at, m.closed_at, m.closed_by
from public.manual_occurrences m
join public.sensors s on s.id = m.sensor_id
join public.monitoring_points p on p.code = s.sensor_code
where not exists (
  select 1 from public.point_occurrences o
  where o.point_id = p.id and o.opened_at = m.created_at and o.reason = m.reason
);

commit;
